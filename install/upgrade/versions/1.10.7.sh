# This release adds IPv6 listen directives to the web and mail (nginx)
# templates, and AAAA record support to the DNS zone templates. Refresh
# all three template sets from the package, then rebuild every user's
# web/mail/dns domain configs so already-existing domains actually pick
# up the refreshed templates - refreshing the template files alone only
# affects domains created (or re-templated) from now on.
#
# Note on DNS specifically: rebuilding an existing domain's zone
# (upgrade_rebuild_users -> v-rebuild-dns-domains) only regenerates the
# on-disk zone file from that domain's already-stored records - it does
# not re-run the zone template, so this does NOT retroactively add AAAA
# records to already-existing domains. Only domains created, or
# explicitly re-templated, after this upgrade will get one. That's
# intentional: silently rewriting DNS data an admin may have hand-edited
# would be a more invasive change than refreshing a web server config.
upgrade_config_set_value 'UPGRADE_UPDATE_WEB_TEMPLATES' 'true'
upgrade_config_set_value 'UPGRADE_UPDATE_DNS_TEMPLATES' 'true'
upgrade_config_set_value 'UPGRADE_UPDATE_MAIL_TEMPLATES' 'true'
upgrade_config_set_value 'UPGRADE_REBUILD_USERS' 'true'

# Neither of those two steps touches the one catch-all vhost Hestia
# renders per *system IP* rather than per domain
# (/etc/$WEB_SYSTEM/conf.d/$ip.conf, and, when a proxy system is
# configured, /etc/$PROXY_SYSTEM/conf.d/$ip.conf) - those are only
# ever (re)generated by v-add-sys-ip itself, when an IP is first
# added. Regenerate them here for every IP that already exists, so
# they also get an IPv6 listener; harmless to re-run even if nothing
# about a given IP changes.
#
# shellcheck source=/usr/local/hestia/func/ip.sh
source "$HESTIA/func/ip.sh"
# shellcheck source=/usr/local/hestia/func/domain.sh
source "$HESTIA/func/domain.sh"

for sys_ip in $("$BIN/v-list-sys-ips" plain | cut -f1); do
	write_sys_ip_catchall_configs "$sys_ip"
done

# The firewall now also builds an ip6tables ruleset (mirroring the rules
# open to everyone, plus ICMPv6/neighbour discovery) - apply it now,
# rather than leaving IPv6 wide open until the firewall is next changed.
if [ -n "$FIREWALL_SYSTEM" ]; then
	"$BIN/v-update-firewall"
fi

# Mail: enable IPv6 in exim - mail is accepted over IPv6 (zones now publish
# an AAAA record for the mail host) and sent over IPv6 too, from each mail
# domain's IPv6 address (its "ip" file, rewritten by the user rebuild above).
if [ "$MAIL_SYSTEM" = 'exim4' ] && [ -f /etc/exim4/exim4.conf.template ]; then
	if grep -q '^disable_ipv6 = true$' /etc/exim4/exim4.conf.template; then
		sed -i '/^disable_ipv6 = true$/d' /etc/exim4/exim4.conf.template
		sed -i 's/^hostlist relay_from_hosts = 127.0.0.1$/hostlist relay_from_hosts = <; 127.0.0.1 ; ::1/' /etc/exim4/exim4.conf.template
		"$BIN/v-restart-mail"
	fi
fi

# FTP: vsftpd now listens dual-stack, where the kernel supports IPv6
if [ "$FTP_SYSTEM" = 'vsftpd' ] && [ -f /etc/vsftpd.conf ] && [ -e /proc/net/if_inet6 ]; then
	if grep -q '^listen=YES$' /etc/vsftpd.conf && ! grep -q '^listen_ipv6=YES$' /etc/vsftpd.conf; then
		sed -i -e 's/^listen=YES$/listen=NO/' -e '/^listen_ipv6=/d' /etc/vsftpd.conf
		sed -i '/^listen=NO$/a listen_ipv6=YES' /etc/vsftpd.conf
		"$BIN/v-restart-ftp"
	fi
fi
